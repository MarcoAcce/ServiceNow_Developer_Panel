DUMMY_DELAY_MS: int = 3000
DUMMY_STATUS_CODE: int = 200
DUMMY_SOURCE: str = "dummy data"
PLACEHOLDER_ROW_COUNT: int = 3


class DummyRequestCall(RequestCall):

    def __init__(self, request: RequestSpec, records: list[dict[str, str]], parent: QObject | None = None) -> None:
        super().__init__(request, parent)
        self._records: list[dict[str, str]] = records
        self._timer: QTimer = QTimer(self)
        self._timer.setSingleShot(True)
        self._timer.setInterval(DUMMY_DELAY_MS)
        self._timer.timeout.connect(self._emit_result)
        self._timer.start()

    def is_running(self) -> bool:
        return self._timer.isActive()

    def cancel(self) -> None:
        self._timer.stop()

    def _emit_result(self) -> None:
        self.succeeded.emit(
            RequestResult(
                request=self.request,
                records=self._records,
                status_code=DUMMY_STATUS_CODE,
                elapsed_ms=DUMMY_DELAY_MS,
                source=DUMMY_SOURCE,
            )
        )


class DummyRequestService(RequestService):

    name: str = DUMMY_SOURCE

    def send(self, request: RequestSpec) -> RequestCall:
        return DummyRequestCall(request, self._records_of(request), self)

    def describe(self) -> str:
        return f"{self.name}, answered after {DUMMY_DELAY_MS // 1000} seconds"

    def _records_of(self, request: RequestSpec) -> list[dict[str, str]]:
        records = DUMMY_RECORDS.get(request.request_type.key)
        if records is None:
            return self._placeholder_records(request)
        return [dict(record) for record in records]

    def _placeholder_records(self, request: RequestSpec) -> list[dict[str, str]]:
        return [
            {column: f"{column} {index + 1}" for column in request.columns}
            for index in range(PLACEHOLDER_ROW_COUNT)
        ]



